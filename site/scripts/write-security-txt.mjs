/**
 * Generate `static/.well-known/security.txt` (RFC 9116).
 *
 * Written rather than committed for one reason: `Expires` is a REQUIRED field
 * (RFC 9116 §2.5.5) and a file past it is meant to be disregarded entirely.
 * A hand-maintained date would be a promise nobody here is reminded to keep —
 * there is no CI, and a deploy ships one person's working tree — so an
 * abandoned file would go on advertising a contact long after anyone checked
 * it. Generating it at build time inverts that: the expiry rolls forward on
 * every deploy, and a site nobody has deployed in a year lets its own
 * security.txt lapse, which is exactly what the field is for.
 *
 * `CONTACT_EMAIL` comes from `src/lib/colophon.ts`, which is where the address
 * the colophon publishes already lives. One constant, two consumers: changing
 * the address changes both, and neither can quietly disagree with the other
 * about how to reach us.
 *
 * The expiry is floored to UTC midnight so that rebuilding on the same day
 * produces a byte-identical file — Wrangler dedupes uploads by content hash,
 * and a timestamp to the millisecond would re-upload this on every deploy.
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { CONTACT_EMAIL } from '../src/lib/colophon.ts';

const siteRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const SECURITY_TXT_PATH = path.join(siteRoot, 'static/.well-known/security.txt');

/**
 * RFC 9116 §2.5.5 recommends less than a year. A year exactly is the longest
 * value that stays inside that advice while asking the least of a project with
 * one maintainer.
 */
const VALIDITY_DAYS = 365;

const CANONICAL = 'https://glossacatholica.org/.well-known/security.txt';

/** UTC midnight, `VALIDITY_DAYS` out. */
export function expiryFrom(now) {
	const at = new Date(now);
	at.setUTCHours(0, 0, 0, 0);
	at.setUTCDate(at.getUTCDate() + VALIDITY_DAYS);
	return at.toISOString().replace('.000Z', 'Z');
}

export function securityTxt(now) {
	if (!CONTACT_EMAIL) {
		throw new Error(
			'write-security-txt: CONTACT_EMAIL is null in src/lib/colophon.ts. `Contact` is the one ' +
				'required field of RFC 9116; a security.txt without it is invalid, and an invalid one ' +
				'is worse than none.'
		);
	}
	return `# Glossa Catholica -- security contact.
#
# Generated by site/scripts/write-security-txt.mjs. Do not edit: the address
# lives in src/lib/colophon.ts (one constant, shared with the colophon) and
# Expires rolls forward on every deploy.
#
# What is here to report against: this site is a static asset host plus a
# 73-line Cloudflare edge worker whose entire job is deciding whether a URL is
# a canonical citation. There is no server-side application, no database, no
# account, no login, no session, no payment path, and no user data of any kind
# -- reading position, bookmarks and preferences never leave the browser's own
# localStorage. There is no advertising and no third-party script.
#
# Reports about missing security headers, or automated scanner output with no
# demonstrated impact, are unlikely to be actionable. Anything touching the
# integrity of the texts themselves is very much of interest: the corpus is a
# verbatim reproduction of editions published elsewhere, and a defect that
# alters what a reader believes the source says is the failure that matters
# most here.

Contact: mailto:${CONTACT_EMAIL}
Expires: ${expiryFrom(now)}
Preferred-Languages: en, pt
Canonical: ${CANONICAL}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	mkdirSync(path.dirname(SECURITY_TXT_PATH), { recursive: true });
	writeFileSync(SECURITY_TXT_PATH, securityTxt(new Date()));
	console.log(`[security-txt] wrote ${SECURITY_TXT_PATH}`);
}
